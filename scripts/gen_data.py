n_text_values = 0
for row in ws.iter_rows(min_row=2, max_row=ws.max_row, max_col=17):
    vals = [c.value for c in row]
    if not any(v is not None and str(v).strip() != '' for v in vals[:6]):
        continue
    d = {}
    for i, h in enumerate(HEADERS):
        v = vals[i]
        if h in ('数值-披露', '数值-换算'):
            if isinstance(v, (int, float)):
                d[h] = float(v)
            elif v is None or str(v).strip() == '':
                d[h] = None
            else:
                # 文本值（如折现率区间 '1.71%~4.72%'、置信水平 '75%'、'不适用'）
                s = str(v).strip()
                d[h] = s
                if h == '数值-换算' and not s.replace('.', '').replace('-', '').isdigit():
                    n_text_values += 1
        elif h == '行序号' or h == '列序号':
            d[h] = v if isinstance(v, int) else (int(v) if isinstance(v, float) and v == int(v) else v)
        else:
            d[h] = None if v is None else str(v).strip()
    # 报告期统一
    if d['报告期'] in PERIOD_FIX:
        d['报告期'] = PERIOD_FIX[d['报告期']]
    raw_rows.append(d)

